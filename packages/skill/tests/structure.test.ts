import { describe, it, expect } from 'vitest'
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const skillDir = fileURLToPath(new URL('../skills/bsv-dev/', import.meta.url))
const skill = readFileSync(skillDir + 'SKILL.md', 'utf8')
const fm = skill.match(/^---\n([\s\S]*?)\n---/)![1]
const repoRoot = fileURLToPath(new URL('../../../', import.meta.url))
const commandsDir = fileURLToPath(new URL('../commands/', import.meta.url))

describe('SKILL.md', () => {
  it('has name bsv-dev and a description under 1024 chars', () => {
    expect(fm).toMatch(/^name: bsv-dev$/m)
    const d = fm.match(/^description: '([\s\S]*?)'$/m)![1]
    expect(d.length).toBeLessThanOrEqual(1024)
  })

  it('body is under 500 lines (target 250)', () => {
    expect(skill.split('\n').length).toBeLessThan(500)
  })

  it('has the six sections in order', () => {
    const idx = [
      '## What this skill is for',
      '## Default decisions',
      '## Agent safety',
      '## Tools to use',
      '## Operating procedure',
      '## Read when needed',
    ].map((h) => skill.indexOf(h))
    expect(idx.every((i) => i >= 0)).toBe(true)
    expect([...idx].sort((a, b) => a - b)).toEqual(idx)
  })

  // Calls npm, so it runs only with SKILLS_REF_TESTS=1; CI's `skill` job runs `skills-ref validate` directly.
  it.skipIf(!process.env.SKILLS_REF_TESTS)('passes skills-ref validate', () => {
    expect(() =>
      execFileSync('npx', ['-y', 'skills-ref@0.1.5', 'validate', skillDir], { stdio: 'pipe' }),
    ).not.toThrow()
  }, 120_000)
})

describe('SKILL.md frontmatter', () => {
  it('equals the spec §6.1 frontmatter exactly', () => {
    const spec = readFileSync(repoRoot + 'docs/superpowers/specs/2026-10-22-bsv-ai-devkit-design.md', 'utf8')
    const section = spec.slice(spec.indexOf('### 6.1 `SKILL.md`'))
    const block = section.match(/```yaml\n([\s\S]*?)\n```/)![1]
    expect(fm).toBe(block)
  })
})

describe('SKILL.md links', () => {
  const table = skill.slice(skill.indexOf('## Read when needed'))
  const routed = [...table.matchAll(/`references\/([^`]+\.md)`/g)].map((m) => m[1])

  it('every routing-table target exists and every reference is routed', () => {
    expect(routed.length).toBeGreaterThan(0)
    for (const f of routed) expect(existsSync(skillDir + 'references/' + f), f).toBe(true)
    expect(readdirSync(skillDir + 'references').sort()).toEqual([...new Set(routed)].sort())
  })

  it('every references/, assets/ and scripts/ path it names exists', () => {
    const paths = [...skill.matchAll(/(?<![\w/.-])((?:references|assets|scripts)\/[\w.-]+)/g)].map((m) => m[1])
    expect(paths.some((p) => p.startsWith('assets/'))).toBe(true)
    expect(paths.some((p) => p.startsWith('scripts/'))).toBe(true)
    for (const p of paths) expect(existsSync(skillDir + p), p).toBe(true)
  })

  it('no link deeper than one level', () => {
    expect(skill).not.toMatch(/references\/[^\s`)]*\/[^\s`)]*\.md/)
    expect(skill).not.toContain('../')
  })

  // packages/sync renders these five (render.ts); the rest are authored. The table marks a subset as (generated).
  it('generated references carry the generated header, and only they do', () => {
    const generated = ['custody-shapes.md', 'facts.md', 'guardrails.md', 'stack.md', 'threat-model.md']
    for (const m of table.matchAll(/`references\/([^`]+\.md)` \(generated\)/g)) expect(generated).toContain(m[1])
    for (const f of readdirSync(skillDir + 'references')) {
      const head = readFileSync(skillDir + 'references/' + f, 'utf8').split('\n')[0]
      const marked = /^<!-- generated by packages\/sync from @bsv\/mcp content v[\d.]+; do not edit; verified dates inside -->$/.test(head)
      expect(marked, f).toBe(generated.includes(f))
    }
  })
})

describe('slash command paths', () => {
  const prefix = '${CLAUDE_PLUGIN_ROOT}/skills/bsv-dev/'
  for (const file of readdirSync(commandsDir).filter((f) => f.endsWith('.md'))) {
    it(`${file} names every skill path under ${prefix}`, () => {
      const md = readFileSync(commandsDir + file, 'utf8')
      const bare = [...md.matchAll(/\b(?:references|assets|scripts)\/[\w.-]+/g)]
        .filter((m) => !md.slice(0, m.index).endsWith(prefix))
        .map((m) => m[0])
      expect(bare).toEqual([])
    })
  }
})
