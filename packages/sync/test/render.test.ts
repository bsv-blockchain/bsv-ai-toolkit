import { describe, it, expect } from 'vitest'
import { fileURLToPath } from 'node:url'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { parse as parseYaml } from 'yaml'
import { renderAll, writeOrCheck } from '../src/render.js'

const contentDir = fileURLToPath(new URL('../../../content', import.meta.url))
const HEADER = '<!-- generated by packages/sync from @bsv/mcp content v2.0.0; do not edit; verified dates inside -->\n'

describe('renderAll', () => {
  it('produces the mcp snapshot and the skill references', async () => {
    const out = await renderAll({ contentDir, mcpOut: 'packages/mcp/content', skillRefsOut: 'packages/skill/skills/bsv-dev/references', version: '2.0.0' })
    for (const p of ['packages/mcp/content/guardrails.json', 'packages/mcp/content/docs-index.json', 'packages/mcp/content/facts/arcade.md',
      'packages/skill/skills/bsv-dev/references/facts.md', 'packages/skill/skills/bsv-dev/references/guardrails.md', 'packages/skill/skills/bsv-dev/references/stack.md',
      'packages/skill/skills/bsv-dev/references/custody-shapes.md', 'packages/skill/skills/bsv-dev/references/threat-model.md']) expect(out.has(p), p).toBe(true)
  })
  it('renders one ### G-xx heading per guardrail', async () => {
    const out = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    const g = out.get('s/guardrails.md')!
    expect(g.match(/^### G-\d\d /gm)).toHaveLength(38)
    expect(g.startsWith('<!-- generated by packages/sync from @bsv/mcp content v2.0.0')).toBe(true)
  })
  it('is deterministic', async () => {
    const a = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    const b = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    expect([...a.entries()]).toEqual([...b.entries()])
  })
  it('copies content/ verbatim into the mcp snapshot and adds the JSON forms', async () => {
    const out = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    expect(out.get('m/facts/arcade.md')).toBe(readFileSync(join(contentDir, 'facts/arcade.md'), 'utf8'))
    expect(out.get('m/versions.json')).toBe(readFileSync(join(contentDir, 'versions.json'), 'utf8'))
    expect(out.get('m/guardrails.yaml')).toBe(readFileSync(join(contentDir, 'guardrails.yaml'), 'utf8'))
    expect(JSON.parse(out.get('m/guardrails.json')!)).toEqual(parseYaml(readFileSync(join(contentDir, 'guardrails.yaml'), 'utf8')))
    expect(JSON.parse(out.get('m/docs-index.json')!)).toEqual(parseYaml(readFileSync(join(contentDir, 'docs-index.yaml'), 'utf8')))
  })
  it('every skill reference starts with the generated header and has no frontmatter', async () => {
    const out = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    for (const name of ['facts', 'guardrails', 'stack', 'custody-shapes', 'threat-model']) {
      const body = out.get(`s/${name}.md`)!
      expect(body.startsWith(HEADER), name).toBe(true)
      expect(body, name).not.toMatch(/^---$/m)
      expect(body.endsWith('\n') && !body.endsWith('\n\n'), name).toBe(true)
    }
  })
  it('facts.md puts each fact file under ## <title> with its verified date and demoted headings', async () => {
    const out = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    const facts = out.get('s/facts.md')!
    expect(facts.match(/^# /gm)).toHaveLength(1)
    expect(facts.match(/^## /gm)).toHaveLength(11) // ten fact files plus Docs links
    expect(facts).toContain('## Arcade broadcaster\n\nverified: 2026-10-22\n')
    expect(facts).toContain('\n### Endpoints\n')
    expect(facts).not.toMatch(/^## Endpoints$/m)
    expect(facts).not.toContain('source: "@bsv/mcp content"')
  })
  it('facts.md leaves # lines inside fenced code alone', async () => {
    const d = mkdtempSync(join(tmpdir(), 'r-'))
    mkdirSync(join(d, 'facts'))
    writeFileSync(join(d, 'facts', 'x.md'), '---\ntitle: X fact\nverified: 2026-01-02\n---\n\n# X\n\nintro\n\n## Part\n\n```sh\n# a shell comment\n```\n')
    writeFileSync(join(d, 'guardrails.yaml'), '[]\n')
    writeFileSync(join(d, 'docs-index.yaml'), 'hosts: ["https://h/"]\nids: {}\n')
    writeFileSync(join(d, 'versions.json'), JSON.stringify({ verified: '2026-01-02', packages: {}, git: {}, services: {}, runtime: {} }))
    for (const f of ['custody-shapes.md', 'threat-model.md']) writeFileSync(join(d, f), '---\ntitle: T\nverified: 2026-01-02\n---\n\n# T\n\nbody\n')
    const out = await renderAll({ contentDir: d, mcpOut: 'm', skillRefsOut: 's', version: '9.9.9' })
    expect(out.get('s/facts.md')).toContain('## X fact\n\nverified: 2026-01-02\n\nintro\n\n### Part\n\n```sh\n# a shell comment\n```\n')
    expect(out.get('s/threat-model.md')).toBe('<!-- generated by packages/sync from @bsv/mcp content v9.9.9; do not edit; verified dates inside -->\n\n# T\n\nverified: 2026-01-02\n\nbody\n')
  })
  it('stack.md tabulates versions.json', async () => {
    const out = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    const stack = out.get('s/stack.md')!
    expect(stack).toContain('| package | pinned | verified | note |')
    expect(stack).toContain('| `@bsv/sdk` | 3.2.1 | 2026-10-22 |  |')
    expect(stack).toContain('| `runar-sdk` | 0.4.6 | 2026-10-22 | npm is stale and unsafe; use git.runar |')
    expect(stack).toMatch(/^## Git sources$/m)
    expect(stack).toContain('d207ee8')
    expect(stack).toMatch(/^## Services$/m)
    expect(stack).toContain('https://arcade-testnet-us-1.bsvblockchain.tech')
    expect(stack).toContain('verified: 2026-10-22')
  })
  it('guardrails.md carries the versions.json verified date under its title', async () => {
    const out = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    expect(out.get('s/guardrails.md')!.startsWith(`${HEADER}\n# Guardrails\n\nverified: 2026-10-22\n`)).toBe(true)
  })
  it('facts.md closes with a Docs links section listing every docs-index id on every host, sorted by id', async () => {
    const out = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    const facts = out.get('s/facts.md')!
    const section = facts.slice(facts.indexOf('\n## Docs links\n'))
    expect(section.length).toBeGreaterThan(0)
    expect(section.slice(1).match(/^## /gm)).toHaveLength(1)
    const index = parseYaml(readFileSync(join(contentDir, 'docs-index.yaml'), 'utf8')) as { hosts: string[]; ids: Record<string, { path: string; title: string; legacy?: string }> }
    const lines = section.split('\n').filter((l) => l.startsWith('- '))
    expect(lines).toHaveLength(Object.keys(index.ids).length)
    expect(lines.map((l) => /`([^`]+)`/.exec(l)![1])).toEqual(Object.keys(index.ids).sort())
    expect(section).toContain('- Gate an API behind payments (`guides.payments`): https://bsv.writedocs.io/docs/guides/payments, https://docs.bsvblockchain.org/docs/guides/payments\n')
    expect(section).toContain('- Wallet API reference (createAction) (`reference.wallet-api`): https://bsv.writedocs.io/docs/reference/wallet-api, https://docs.bsvblockchain.org/docs/reference/wallet-api; legacy https://bsv.writedocs.io/reference/wallet-api/actions/post-createaction.md\n')
  })
  it('guardrails.md carries rule, why, detect, shape and refs for each rule', async () => {
    const out = await renderAll({ contentDir, mcpOut: 'm', skillRefsOut: 's', version: '2.0.0' })
    const g = out.get('s/guardrails.md')!
    const section = g.slice(g.indexOf('### G-01 Wallet connection and identity'), g.indexOf('### G-02 '))
    for (const label of ['Rule', 'Why', 'Shape', 'Detect', 'Severity', 'Refs']) expect(section).toContain(`**${label}:**`)
    expect(section).toContain('`brc:73`')
  })
})

describe('writeOrCheck', () => {
  function setup() {
    const d = mkdtempSync(join(tmpdir(), 'w-'))
    mkdirSync(join(d, 'out'))
    writeFileSync(join(d, 'out', 'same.md'), 'same\n')
    writeFileSync(join(d, 'out', 'changed.md'), 'old\n')
    writeFileSync(join(d, 'out', 'stale.md'), 'stale\n')
    const files = new Map([
      [join(d, 'out', 'same.md'), 'same\n'],
      [join(d, 'out', 'changed.md'), 'new\n'],
      [join(d, 'out', 'sub', 'added.md'), 'added\n'],
    ])
    return { d, files }
  }
  it('check mode reports differing paths without writing', async () => {
    const { d, files } = setup()
    const diff = await writeOrCheck(files, true, [join(d, 'out')])
    expect(diff.sort()).toEqual([join(d, 'out', 'changed.md'), join(d, 'out', 'stale.md'), join(d, 'out', 'sub', 'added.md')].sort())
    expect(readFileSync(join(d, 'out', 'changed.md'), 'utf8')).toBe('old\n')
    expect(existsSync(join(d, 'out', 'sub', 'added.md'))).toBe(false)
    expect(existsSync(join(d, 'out', 'stale.md'))).toBe(true)
  })
  it('write mode writes changes, removes stale files in owned dirs, then reports nothing', async () => {
    const { d, files } = setup()
    await writeOrCheck(files, false, [join(d, 'out')])
    expect(readFileSync(join(d, 'out', 'changed.md'), 'utf8')).toBe('new\n')
    expect(readFileSync(join(d, 'out', 'sub', 'added.md'), 'utf8')).toBe('added\n')
    expect(existsSync(join(d, 'out', 'stale.md'))).toBe(false)
    expect(await writeOrCheck(files, true, [join(d, 'out')])).toEqual([])
  })
  it('leaves files outside owned dirs alone', async () => {
    const { d, files } = setup()
    expect(await writeOrCheck(files, true)).not.toContain(join(d, 'out', 'stale.md'))
  })
})
